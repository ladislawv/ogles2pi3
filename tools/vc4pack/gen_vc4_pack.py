#!/usr/bin/env python3
"""Packet packers for the VideoCore IV 3D core (V3D 2.1) from Mesa's
vc4_packet.xml (src/broadcom/cle/, MIT): vc4core/include/vc4_pack.h.

Like Mesa's gen_pack_header.py (the same field names, so its packers can be
compared with these: --test), but every byte is stored by itself with 32-bit
arithmetic: right on the big-endian 68k as on the Pi, and cheap there (Mesa's
packers shift 64-bit values and copy 32-bit fields with memcpy in the host's
byte order). Packets only: the XML's two structs (shader and attribute
records) have overlapping fields, so vc4core writes those records itself, as
Mesa's vc4 driver does.

    gen_vc4_pack.py vc4_packet.xml > vc4_pack.h
    gen_vc4_pack.py --test vc4_packet.xml > test.c   (compares with Mesa's)

MIT licence (LICENSE).
"""
import random
import sys
import xml.etree.ElementTree as ET

SUBST = {' ': '_', '/': '_', '[': '', ']': '', '(': '', ')': '', '-': '_', ':': '', '.': '', ',': '',
         '=': '', '>': '', '#': '', '&': '', '*': '', '"': '', '+': '', '\'': ''}


def safe_name(name):
    """Mesa's gen_pack_header.py: to_alphanum and safe_name."""
    for a, b in SUBST.items():
        name = name.replace(a, b)
    if not name[0].isalpha():
        name = '_' + name
    return name


class Field:
    def __init__(self, el, enums):
        self.name = safe_name(el.get('name')).lower()
        start = el.get('start')
        self.start = (int(start[:-1]) * 8 if start.endswith('b') else int(start)) + 8  # after the opcode
        self.size = int(el.get('size'))
        self.end = self.start + self.size - 1
        t = el.get('type')
        if t in enums:
            t = 'uint'
        self.type = t
        self.values = [(safe_name(v.get('name')).upper(), int(v.get('value'), 0)) for v in el.findall('value')]
        assert t in ('uint', 'bool', 'int', 'address', 'float', 's12.4'), (self.name, t)
        if t == 'float':
            assert self.size == 32 and self.start % 8 == 0
        if t == 'uint' and self.size > 32:
            assert self.size == 64 and self.start % 8 == 0
        if t == 'address':
            assert (self.start - (32 - self.size)) % 8 == 0  # the address's whole word starts on a byte

    def ctype(self):
        if self.type in ('float', 's12.4'):
            return 'float'
        if self.type == 'uint' and self.size > 32:
            return 'uint64_t'
        if self.type == 'int':
            return 'int32_t'
        return 'uint32_t'

    def mask(self):
        return '0x%xu' % ((1 << self.size) - 1) if self.size < 32 else None

    def word(self):
        """(C expression of the field's 32-bit value, the packet bit it starts at)"""
        v = 'v->%s' % self.name
        if self.type == 'address':
            low = 32 - self.size
            e = '(%s & ~0x%xu)' % (v, (1 << low) - 1) if low else v
            return e, self.start - low
        if self.type == 'float':
            return 'vc4_fbits(%s)' % v, self.start
        if self.type == 's12.4':
            return '((uint32_t)vc4_sfixed4(%s) & 0xffffu)' % v, self.start
        e = '(uint32_t)%s' % v
        if self.mask():
            e = '(%s & %s)' % (e, self.mask())
        return e, self.start

    def byte(self, i):
        """The field's contribution to byte i, or None."""
        if self.type == 'uint' and self.size == 64:
            k = i - self.start // 8
            if not 0 <= k < 8:
                return None
            half = '(uint32_t)v->%s' % self.name if k < 4 else '(uint32_t)(v->%s >> 32)' % self.name
            return '(uint8_t)(%s >> %d)' % (half, 8 * (k % 4)) if k % 4 else '(uint8_t)%s' % half
        e, s = self.word()
        width = 32 if self.type in ('address', 'float') else (16 if self.type == 's12.4' else self.size)
        lo, hi = s, s + width - 1
        if hi < 8 * i or lo > 8 * i + 7:
            return None
        d = s - 8 * i
        if d > 0:
            return '(uint8_t)(%s << %d)' % (e, d)
        if d < 0:
            return '(uint8_t)(%s >> %d)' % (e, -d)
        return '(uint8_t)%s' % e


def packets(root):
    enums = {e.get('name') for e in root.findall('enum')}
    out = []
    for p in root.findall('packet'):
        name = safe_name(p.get('name')).upper()
        fields = [Field(f, enums) for f in p.findall('field')]
        length = max([f.end // 8 for f in fields] + [0]) + 1
        out.append((name, int(p.get('code')), length, fields))
    return out


def header(root):
    print('/* Generated by tools/vc4pack/gen_vc4_pack.py from Mesa\'s')
    print(' * src/broadcom/cle/vc4_packet.xml; do not edit. The XML is under the MIT')
    print(' * licence (Copyright Broadcom, Mesa\'s contributors). */')
    print('#ifndef VC4_PACK_H\n#define VC4_PACK_H\n\n#include <stdint.h>\n')
    print('static inline uint32_t vc4_fbits(float f)\n{\n    union { float f; uint32_t u; } x;\n    x.f = f;\n    return x.u;\n}\n')
    print('/* s12.4: nearest, halves away from zero (as Mesa\'s util_bitpack_sfixed) */')
    print('static inline int32_t vc4_sfixed4(float f)\n{\n    return (int32_t)(f * 16.0f + (f < 0.0f ? -0.5f : 0.5f));\n}\n')
    for e in root.findall('enum'):
        prefix = safe_name(e.get('prefix')).upper()
        for v in e.findall('value'):
            print('#define VC4_%s_%s %s' % (prefix[4:] if prefix.startswith('V3D_') else prefix,
                                           safe_name(v.get('name')).upper(), v.get('value')))
        print()
    seen = {}
    for name, code, length, fields in packets(root):
        print('#define VC4_%s_opcode %d' % (name, code))
        print('#define VC4_%s_length %d' % (name, length))
        for f in fields:
            for vn, vv in f.values:
                d = 'VC4_%s_%s' % (f.name.upper(), vn)
                if seen.get(d, vv) != vv:
                    d = 'VC4_%s_%s_%s' % (name, f.name.upper(), vn)
                seen[d] = vv
                print('#define %s %d' % (d, vv))
        if fields:
            print('struct VC4_%s {' % name)
            for f in fields:
                print('    %s %s;' % (f.ctype(), f.name))
            print('};')
            print('static inline void VC4_%s_pack(uint8_t *cl, const struct VC4_%s *v)\n{' % (name, name))
        else:
            print('static inline void VC4_%s_pack(uint8_t *cl)\n{' % name)
        print('    cl[0] = %d;' % code)
        for i in range(1, length):
            parts = [x for x in (f.byte(i) for f in fields) if x]
            print('    cl[%d] = %s;' % (i, ' | '.join(parts) if parts else '0'))
        print('}\n')
    print('#endif')


def test(root):
    """A program comparing these packers with Mesa's generated ones."""
    rnd = random.Random(1)
    print('#include <stdio.h>\n#include <string.h>\n#include <stdint.h>\n#include <stdbool.h>')
    print('#define __gen_user_data void\n#define __gen_address_type uint32_t')
    print('#define __gen_address_offset(r) (*(r))\n#define __gen_emit_reloc(d, r)')
    print('#include "broadcom/cle/v3d_packet_v21_pack.h"\n#include "vc4_pack.h"\n')
    print('static uint32_t s = 12345;')
    print('static uint32_t rnd32(void) { s = s * 1103515245u + 12345u; return (s >> 8) ^ (s << 21); }\n')
    print('int main(void)\n{\n    int bad = 0, n = 0, k;\n    uint8_t a[64], b[64];')
    for name, code, length, fields in packets(root):
        if not fields:
            continue
        print('    for (k = 0; k < 200; k++) {')
        print('        struct V3D21_%s m = {V3D21_%s_header};\n        struct VC4_%s o;' % (name, name, name))
        for f in fields:
            if f.type == 'address':
                val = 'rnd32() & ~0x%xu' % ((1 << (32 - f.size)) - 1)
            elif f.type == 'float':
                val = '(float)(int32_t)rnd32() / 65536.0f'
            elif f.type == 's12.4':
                val = '(float)((int32_t)(rnd32() & 0xffff) - 32768) / 16.0f'
            elif f.type == 'uint' and f.size == 64:
                val = '((uint64_t)rnd32() << 32) | rnd32()'
            elif f.type == 'int':
                val = '(int32_t)(rnd32() << (32 - %d)) >> (32 - %d)' % (f.size, f.size)
            else:
                val = 'rnd32() & 0x%xu' % ((1 << f.size) - 1 if f.size < 32 else 0xffffffff)
            print('        m.%s = o.%s = (%s);' % (f.name, f.name, val))
        print('        memset(a, 0, sizeof(a));\n        memset(b, 0, sizeof(b));')
        print('        V3D21_%s_pack(NULL, a, &m);\n        VC4_%s_pack(b, &o);' % (name, name))
        print('        n++;\n        if (memcmp(a, b, %d)) {\n            if (bad++ < 5) printf("%s differs\\n");\n        }\n    }' % (length, name))
    print('    printf("%d packets packed, %d differ\\n", n, bad);\n    return bad != 0;\n}')


if __name__ == '__main__':
    args = sys.argv[1:]
    t = args and args[0] == '--test'
    root = ET.parse(args[-1]).getroot()
    if t:
        test(root)
    else:
        header(root)
