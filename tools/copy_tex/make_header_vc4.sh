#!/bin/bash
# Compiles the program glCopyTex* draws with on the GPU (copy.c, draw.c; as
# make_header.sh for the Pi 4) for the Pi 3, with the variants of the copies it
# can draw (keys_vc4.c), and writes it into ogles2/vc4/copy_tex_vc4p.h as a .vc4p
# image the library loads from memory, with its sources (a copy in another state
# compiles its variants at run time). Run in WSL after the host v3dglslc changes
# (the file records the Mesa commit the loader checks):
#   bash tools/copy_tex/make_header_vc4.sh
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
V3DGLSLC=${V3DGLSLC:-$HOME/ogles2-build-pi3/v3dglslc/host/v3dglslc}
W=$(mktemp -d)
cp "$HERE/copy_tex.vert" "$HERE/copy_tex.frag" "$W/"
gcc -O2 -Wall -I"$REPO/ogles2/vc4" -I"$REPO/vc4core/include" -o "$W/keys" "$HERE/keys_vc4.c" "$REPO/ogles2/vc4/key_vc4.c"
"$W/keys" "$W/copy.keys"
(cd "$W" && "$V3DGLSLC" -g 21 -k copy.keys -o . copy_tex.vert copy_tex.frag > log.txt 2>&1) || { cat "$W/log.txt"; exit 1; }
python3 - "$W/copy_tex-copy_tex.vc4p" "$REPO/ogles2/vc4/copy_tex_vc4p.h" "$HERE/copy_tex.vert" "$HERE/copy_tex.frag" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
def cstr(path):
    t = open(path).read()
    return "\n".join('    "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in t.rstrip("\n").split("\n"))
out = ["/* Generated by tools/copy_tex/make_header_vc4.sh from copy_tex.vert, copy_tex.frag",
       " * and keys_vc4.c: do not edit. The program draw.c draws glCopyTex* with on the",
       " * Pi 3 (copy.c) as a .vc4p image (v3dp/FORMAT.md 1.1), and its sources for the",
       " * variants of other states. */",
       "static const UBYTE copy_tex_vc4p[%d] = {" % len(data)]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
out.append("};")
out.append("static const char copy_tex_vc4_vs[] =")
out.append(cstr(sys.argv[3]) + ";")
out.append("static const char copy_tex_vc4_fs[] =")
out.append(cstr(sys.argv[4]) + ";")
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
print("%s: %d bytes" % (sys.argv[2], len(data)))
PY
python3 "$REPO/v3dp/v3dp_dump.py" "$W/copy_tex-copy_tex.vc4p" | grep -E "attrib|uniform|VC4_VARIANT" | head -30
rm -rf "$W"
