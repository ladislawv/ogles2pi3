#!/bin/bash
# Compiles the program the VC4 backend draws clears of part of a
# framebuffer with (its built-in image: ogles2/draw.c's ogles2_draw_clear,
# a matrix uniform, position and colour attributes, as the V3D one's) for
# the Pi 3, with the variants of the usual clear states (keys.c), and writes
# it into ogles2/vc4/builtin_vc4p.h as a .vc4p image the library loads from
# memory, with its sources (a clear in another state compiles its variants
# at run time). Run in WSL after the host v3dglslc changes (the file records
# the Mesa commit the loader checks):  bash tools/clear_vc4/make_header.sh
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
V3DGLSLC=${V3DGLSLC:-$HOME/ogles2-build-pi3/v3dglslc/host/v3dglslc}
W=$(mktemp -d)
cp "$HERE/clear.vert" "$HERE/clear.frag" "$W/"
gcc -O2 -Wall -I"$REPO/ogles2/vc4" -I"$REPO/vc4core/include" -o "$W/keys" "$HERE/keys.c" "$REPO/ogles2/vc4/key_vc4.c"
"$W/keys" "$W/clear.keys"
(cd "$W" && "$V3DGLSLC" -g 21 -k clear.keys -o . clear.vert clear.frag > log.txt 2>&1) || { cat "$W/log.txt"; exit 1; }
python3 - "$W/clear-clear.vc4p" "$REPO/ogles2/vc4/builtin_vc4p.h" "$HERE/clear.vert" "$HERE/clear.frag" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
def cstr(path):
    t = open(path).read()
    return "\n".join('    "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in t.rstrip("\n").split("\n"))
out = ["/* Generated by tools/clear_vc4/make_header.sh from clear.vert, clear.frag",
       " * and keys.c: do not edit. The VC4 backend's built-in image (clears of",
       " * part of a framebuffer, ogles2/draw.c) as a .vc4p image (v3dp/FORMAT.md",
       " * 1.1), and its sources for the variants of other states. */",
       "static const UBYTE builtin_vc4p[%d] = {" % len(data)]
for i in range(0, len(data), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
out.append("};")
out.append("static const char builtin_vc4_vs[] =")
out.append(cstr(sys.argv[3]) + ";")
out.append("static const char builtin_vc4_fs[] =")
out.append(cstr(sys.argv[4]) + ";")
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
print("%s: %d bytes" % (sys.argv[2], len(data)))
PY
python3 "$REPO/v3dp/v3dp_dump.py" "$W/clear-clear.vc4p" | grep -E "attrib|uniform|VC4_VARIANT" | head -40
rm -rf "$W"
